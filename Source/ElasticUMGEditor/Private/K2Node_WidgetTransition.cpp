void UK2Node_WidgetTransition::ShowValueTypePinWhenWidgetSelectionIsHidden(const UEdGraphSchema_K2* Schema)
{
	if (IsOptionalPinVisible(EWidgetTransitionOptionalPin::WidgetAndProperty)) return;
	UEdGraphPin* ValueTypePin = CreatePin(EGPD_Input, Schema->PC_Byte, StaticEnum<EWidgetTransitionValueType>(), WidgetTransitionNode::ValueTypePinName);
	ValueTypePin->bNotConnectable = true;
	ValueTypePin->DefaultValue = StaticEnum<EWidgetTransitionValueType>()->GetNameStringByValue(static_cast<int64>(ManualValueType));
}

void UK2Node_WidgetTransition::ShowTransitionValuePins(const UEdGraphSchema_K2* Schema)
{
	if (IsOptionalPinVisible(EWidgetTransitionOptionalPin::From))
	{
		WidgetTransitionNode::CreateValuePin(this, EGPD_Input, WidgetTransitionNode::FromValuePinName, Schema);
		if (bValuePinsDisabled)
		{
			UEdGraphPin* FromPin = FindPinChecked(WidgetTransitionNode::FromValuePinName);
			FromPin->bNotConnectable = true;
			FromPin->bDefaultValueIsReadOnly = true;
		}
	}
	WidgetTransitionNode::CreateValuePin(this, EGPD_Input, WidgetTransitionNode::ToValuePinName, Schema);
	if (bValuePinsDisabled)
	{
		UEdGraphPin* ToPin = FindPinChecked(WidgetTransitionNode::ToValuePinName);
		ToPin->bNotConnectable = true;
		ToPin->bDefaultValueIsReadOnly = true;
	}
}

void UK2Node_WidgetTransition::ShowTimingAndEasingPins(const UEdGraphSchema_K2* Schema)
{
	if (IsOptionalPinVisible(EWidgetTransitionOptionalPin::Delay))
	{
		CreatePin(EGPD_Input, Schema->PC_Real, Schema->PC_Float, WidgetTransitionNode::DelayPinName)->DefaultValue = TEXT("0.0");
		UEdGraphPin* ApplyBeforeDelayPin = CreatePin(EGPD_Input, Schema->PC_Boolean, WidgetTransitionNode::ApplyValueBeforeDelayPinName);
		ApplyBeforeDelayPin->DefaultValue = TEXT("true");
	}
	if (!IsOptionalPinVisible(EWidgetTransitionOptionalPin::Spring)) CreatePin(EGPD_Input, Schema->PC_Real, Schema->PC_Float, WidgetTransitionNode::TimePinName)->DefaultValue = TEXT("0.2");
	if (!IsOptionalPinVisible(EWidgetTransitionOptionalPin::Spring))
	{
		UEdGraphPin* EasingPin = CreatePin(EGPD_Input, Schema->PC_Struct, FWidgetTransitionEasingValue::StaticStruct(), WidgetTransitionNode::EasingPinName);
		WidgetTransitionNode::SetEasingDefault(EasingPin, GetDisplayedEasingValue());
		if (!IsCustomEasingSelected())
		{
			EasingPin->bNotConnectable = true;
			EasingPin->bDefaultValueIsReadOnly = true;
		}
	}
}

