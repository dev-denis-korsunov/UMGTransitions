void UK2Node_WidgetTransition::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);
	// UE 5.7's RecombinePin writes FVector2D as "X=… Y=…", while UHT expects struct text.
	// Normalize after Super so both split and recombined pins compile through this custom node.
	WidgetTransitionNode::NormalizeVector2DDefault(FindPin(WidgetTransitionNode::FromValuePinName));
	WidgetTransitionNode::NormalizeVector2DDefault(FindPin(WidgetTransitionNode::ToValuePinName));
	if (!bValueTypeResolved)
	{
		CompilerContext.MessageLog.Error(*NSLOCTEXT("ElasticUMG", "UnresolvedWidgetTransitionType", "@@ requires a Widget Property to resolve its wildcard value type.").ToString(), this);
		BreakAllNodeLinks();
		return;
	}
	if (bValuePinsDisabled)
	{
		CompilerContext.MessageLog.Error(*NSLOCTEXT("ElasticUMG", "MissingWidgetTransitionProperty", "@@ requires a valid Widget Property while Wp is enabled.").ToString(), this);
		BreakAllNodeLinks();
		return;
	}
	UFunction* Function = WidgetTransitionNode::GetTransitionFunction(ValueType);
	if (!Function) { CompilerContext.MessageLog.Error(*NSLOCTEXT("ElasticUMG", "MissingWidgetTransitionFunction", "@@ could not find its transition function.").ToString(), this); BreakAllNodeLinks(); return; }
	UK2Node_CallFunction* CallNode = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
	CallNode->SetFromFunction(Function); CallNode->AllocateDefaultPins();
	const UEdGraphPin* FromPin = FindPin(WidgetTransitionNode::FromValuePinName);
	const bool bUseFrom = FromPin && (!FromPin->LinkedTo.IsEmpty() || !FromPin->DefaultValue.IsEmpty());
	const auto MoveLinks = [&CompilerContext, this, CallNode](FName PinName)
	{
		if (UEdGraphPin* SourcePin = FindPin(PinName)) if (UEdGraphPin* DestinationPin = CallNode->FindPin(PinName)) CompilerContext.MovePinLinksToIntermediate(*SourcePin, *DestinationPin);
	};
	MoveLinks(WidgetTransitionNode::WidgetPinName); MoveLinks(WidgetTransitionNode::WidgetPropertyPinName); MoveLinks(WidgetTransitionNode::FromValuePinName);
	MoveLinks(WidgetTransitionNode::ToValuePinName);
	if (UEdGraphPin* SourcePin = FindPin(WidgetTransitionNode::TransitionPinName))
	{
		if (UEdGraphPin* DestinationPin = CallNode->GetReturnValuePin()) CompilerContext.MovePinLinksToIntermediate(*SourcePin, *DestinationPin);
	}
	CallNode->FindPinChecked(WidgetTransitionNode::UseFromPinName)->DefaultValue = bUseFrom ? TEXT("true") : TEXT("false");
	if (UEdGraphPin* SpringPin = CallNode->FindPin(WidgetTransitionNode::UseSpringPinName)) SpringPin->DefaultValue = IsOptionalPinVisible(EWidgetTransitionOptionalPin::Spring) ? TEXT("true") : TEXT("false");
	BreakAllNodeLinks();
}

void UK2Node_WidgetTransition::PinDefaultValueChanged(UEdGraphPin* Pin)
{
	Super::PinDefaultValueChanged(Pin);
	if (Pin && Pin->PinName == WidgetTransitionNode::ValueTypePinName)
	{
		const UEnum* ValueTypeEnum = StaticEnum<EWidgetTransitionValueType>();
		const int64 EnumValue = ValueTypeEnum ? ValueTypeEnum->GetValueByNameString(Pin->DefaultValue) : INDEX_NONE;
		if (EnumValue != INDEX_NONE) SetValueType(static_cast<EWidgetTransitionValueType>(EnumValue));
		return;
	}
	if (Pin && Pin->PinName == WidgetTransitionNode::WidgetPropertyPinName && IsOptionalPinVisible(EWidgetTransitionOptionalPin::WidgetAndProperty) && Pin->DefaultValue.IsEmpty())
	{
		Modify();
		bValuePinsDisabled = true;
		ReconstructNode();
		return;
	}
	if (Pin && Pin->PinName == WidgetTransitionNode::RepeatCountPinName)
	{
		const bool bNewInfinite = WidgetTransitionNode::IsInfiniteRepeat(Pin);
		if (bRepeatCountIsInfinite != bNewInfinite) { Modify(); bRepeatCountIsInfinite = bNewInfinite; ReconstructNode(); }
	}
}

void UK2Node_WidgetTransition::NotifyPinConnectionListChanged(UEdGraphPin* Pin)
{
	Super::NotifyPinConnectionListChanged(Pin);
	if (Pin && Pin->PinName == WidgetTransitionNode::RepeatCountPinName)
	{
		const bool bNewInfinite = WidgetTransitionNode::IsInfiniteRepeat(Pin);
		if (bRepeatCountIsInfinite != bNewInfinite) { Modify(); bRepeatCountIsInfinite = bNewInfinite; ReconstructNode(); }
	}
}

void UK2Node_WidgetTransition::PostReconstructNode()
{
	Super::PostReconstructNode();
	for (UEdGraphPin* Pin : Pins) WidgetTransitionNode::NormalizeVector2DDefault(Pin);
	// One-time migration from the earlier Name + two-vector representation.
	for (const UEdGraphPin* Pin : Pins)
	{
		if (!Pin->bOrphanedPin || Pin->PinName != WidgetTransitionNode::EasingPinName || Pin->PinType.PinCategory != UEdGraphSchema_K2::PC_Name) continue;
		const FString LegacyPreset = Pin->GetDefaultAsString();
		if (!LegacyPreset.IsEmpty()) SelectedEasingPreset = FName(*LegacyPreset);
		break;
	}
	if (IsCustomEasingSelected())
	{
		FWidgetTransitionEasingValue LegacyValue = GetDisplayedEasingValue();
		for (const UEdGraphPin* Pin : Pins)
		{
			if (!Pin->bOrphanedPin) continue;
			if (Pin->PinName == WidgetTransitionNode::EasingControlPoint1PinName) LegacyValue.ControlPoint1.InitFromString(Pin->GetDefaultAsString());
			if (Pin->PinName == WidgetTransitionNode::EasingControlPoint2PinName) LegacyValue.ControlPoint2.InitFromString(Pin->GetDefaultAsString());
		}
		WidgetTransitionNode::SetEasingDefault(FindPin(WidgetTransitionNode::EasingPinName), LegacyValue);
	}
	const auto MigrateLegacyToggle = [this](EWidgetTransitionOptionalPin LegacyOption, FName PinName)
	{
		if (!IsOptionalPinVisible(LegacyOption)) return;
		if (UEdGraphPin* Pin = FindPin(PinName))
		{
			Pin->DefaultValue = TEXT("true");
			Pin->AutogeneratedDefaultValue = TEXT("true");
		}
		OptionalPins &= ~static_cast<int32>(LegacyOption);
	};
	// Convert old tab state once; subsequent edits use the regular bool pins.
	MigrateLegacyToggle(EWidgetTransitionOptionalPin::YoYo, WidgetTransitionNode::YoYoPinName);
	MigrateLegacyToggle(EWidgetTransitionOptionalPin::RemoveFromParent, WidgetTransitionNode::RemoveFromParentPinName);
	TArray<UEdGraphPin*> PinsToDiscard;
	for (UEdGraphPin* Pin : Pins)
	{
		if (WidgetTransitionNode::IsDiscardableTypeSpecificPin(Pin)) PinsToDiscard.Add(Pin);
	}
	if (PinsToDiscard.IsEmpty()) return;
	for (UEdGraphPin* Pin : PinsToDiscard) Pins.Remove(Pin);
	DestroyPinList(PinsToDiscard);
}

bool UK2Node_WidgetTransition::CanSplitPin(const UEdGraphPin* Pin) const
{
	return (!Pin || Pin->PinName != WidgetTransitionNode::EasingPinName || IsCustomEasingSelected()) && Super::CanSplitPin(Pin);
}

void UK2Node_WidgetTransition::PostEditChangeProperty(FPropertyChangedEvent& PropertyChangedEvent)
{
	Super::PostEditChangeProperty(PropertyChangedEvent);
	if (PropertyChangedEvent.GetPropertyName() == GET_MEMBER_NAME_CHECKED(UK2Node_WidgetTransition, OptionalPins))
	{
		Modify();
		ReconstructNode();
	}
}

void UK2Node_WidgetTransition::SetValueType(EWidgetTransitionValueType InValueType)
{
	if (!bValueTypeResolved || ValueType != InValueType)
	{
		Modify();
		ValueType = InValueType;
		ManualValueType = InValueType;
		bValueTypeResolved = true;
		bValuePinsDisabled = false;
		if (!SupportsTransitionMode(TEXT("Spring")))
		{
			OptionalPins &= ~static_cast<int32>(EWidgetTransitionOptionalPin::Spring);
			bShowEasing = true;
		}
		ReconstructNode();
	}
}

void UK2Node_WidgetTransition::SetOptionalPins(int32 InOptionalPins)
{
	if (OptionalPins != InOptionalPins)
	{
		Modify();
		const bool bWasShowingWidgetAndProperty = IsOptionalPinVisible(EWidgetTransitionOptionalPin::WidgetAndProperty);
		OptionalPins = InOptionalPins;
		const bool bIsShowingWidgetAndProperty = IsOptionalPinVisible(EWidgetTransitionOptionalPin::WidgetAndProperty);
		if (!bWasShowingWidgetAndProperty && bIsShowingWidgetAndProperty)
		{
			if (const TOptional<EWidgetTransitionValueType> PropertyType = WidgetTransitionNode::GetSelectedPropertyValueType(this))
			{
				ValueType = PropertyType.GetValue();
				bValueTypeResolved = true;
				bValuePinsDisabled = false;
			}
			else bValuePinsDisabled = true;
		}
		else if (bWasShowingWidgetAndProperty && !bIsShowingWidgetAndProperty)
		{
			ValueType = ManualValueType;
			bValueTypeResolved = true;
			bValuePinsDisabled = false;
		}
		ReconstructNode();
	}
}

void UK2Node_WidgetTransition::SetEasingVisible(bool bInShowEasing)
{
	if (bShowEasing != bInShowEasing)
	{
		Modify();
		bShowEasing = bInShowEasing;
		ReconstructNode();
	}
}

void UK2Node_WidgetTransition::SetTransitionMode(bool bInUseSpring)
{
	if (bInUseSpring && !SupportsTransitionMode(TEXT("Spring"))) return;
	Modify();
	int32 NewOptionalPins = OptionalPins;
	if (bInUseSpring) NewOptionalPins |= static_cast<int32>(EWidgetTransitionOptionalPin::Spring);
	else NewOptionalPins &= ~static_cast<int32>(EWidgetTransitionOptionalPin::Spring);
	const bool bNewShowEasing = !bInUseSpring;
	if (OptionalPins == NewOptionalPins && bShowEasing == bNewShowEasing) return;
	OptionalPins = NewOptionalPins;
	bShowEasing = bNewShowEasing;
	ReconstructNode();
}

bool UK2Node_WidgetTransition::IsCustomEasingSelected() const
{
	return SelectedEasingPreset == TEXT("Custom");
}

void UK2Node_WidgetTransition::SetSelectedEasingPreset(FName InPreset)
{
	if (SelectedEasingPreset == InPreset) return;
	Modify();
	SelectedEasingPreset = InPreset;
	ReconstructNode();
}

FWidgetTransitionEasingValue UK2Node_WidgetTransition::GetDisplayedEasingValue() const
{
	FWidgetTransitionEasingValue Value;
	if (!IsCustomEasingSelected())
	{
		if (const FWidgetTransitionEasing* Preset = GetDefault<UWidgetTransitionSettings>()->FindEasing(SelectedEasingPreset))
		{
			Value.ControlPoint1 = Preset->ControlPoint1;
			Value.ControlPoint2 = Preset->ControlPoint2;
		}
		else { Value.ControlPoint1 = FVector2D::ZeroVector; Value.ControlPoint2 = FVector2D(1.0f, 1.0f); }
		return Value;
	}
	if (const UEdGraphPin* EasingPin = FindPin(WidgetTransitionNode::EasingPinName))
	{
		if (EasingPin->SubPins.Num() == 2)
		{
			Value.ControlPoint1.InitFromString(EasingPin->SubPins[0]->GetDefaultAsString());
			Value.ControlPoint2.InitFromString(EasingPin->SubPins[1]->GetDefaultAsString());
		}
		else FWidgetTransitionEasingValue::StaticStruct()->ImportText(*EasingPin->DefaultValue, &Value, nullptr, PPF_None, nullptr, TEXT("Easing"));
	}
	return Value;
}

void UK2Node_WidgetTransition::SetPropertyValueType(EWidgetTransitionValueType InValueType)
{
	Modify();
	ValueType = InValueType;
	bValueTypeResolved = true;
	bValuePinsDisabled = false;
	if (!SupportsTransitionMode(TEXT("Spring")))
	{
		OptionalPins &= ~static_cast<int32>(EWidgetTransitionOptionalPin::Spring);
		bShowEasing = true;
	}
	ReconstructNode();
}
