	Super::PinDefaultValueChanged(Pin);
	EWidgetTransitionValueType NewType;
	if (Pin && Pin->PinName == WidgetTransitionNode::ValueTypePinName && WidgetTransitionNode::ReadType(Pin, NewType) && NewType != ValueType)
	{
		Modify();
		WidgetTransitionNode::ResetTypedValuePin(this, WidgetTransitionNode::FromValuePinName);
		ValueType = NewType;
		ReconstructNode();
	}
