	/** Finds the typed runtime entry point from UFUNCTION metadata rather than a hard-coded name table. */
	static UFunction* GetTransitionFunction(EWidgetTransitionValueType ValueType)
	{
		const FString ExpectedValueType = StaticEnum<EWidgetTransitionValueType>()->GetNameStringByValue(static_cast<int64>(ValueType));
		for (TFieldIterator<UFunction> It(UWidgetTransitionFunctionLibrary::StaticClass()); It; ++It)
		{
			UFunction* Function = *It;
			if (Function->HasMetaData(TEXT("ElasticUMGTransition")) && Function->GetMetaData(TEXT("ElasticUMGValueType")) == ExpectedValueType) return Function;
		}
		return nullptr;
	}

	static const FProperty* FindTransitionParameter(const UFunction* Function, FName Role)
	{
		if (!Function) return nullptr;
		for (TFieldIterator<FProperty> It(Function); It; ++It)
		{
			const FProperty* Property = *It;
			if (Property->GetMetaData(TEXT("ElasticUMGRole")) == Role.ToString()) return Property;
		}
		return FindFProperty<FProperty>(Function, Role);
	}

	static void CreateValuePin(UK2Node_WidgetTransition* Node, EEdGraphPinDirection Direction, FName Name, const UEdGraphSchema_K2* Schema)
	{
		if (!Node->IsValueTypeResolved()) { Node->CreatePin(Direction, Schema->PC_Wildcard, Name); return; }
		UFunction* Function = GetTransitionFunction(Node->GetValueType());
		const FProperty* Parameter = FindTransitionParameter(Function, Name);
		FEdGraphPinType PinType;
		if (!Parameter || !Schema->ConvertPropertyToPinType(Parameter, PinType)) return;
		UEdGraphPin* Pin = Node->CreatePin(Direction, PinType, Name);
		FString DefaultValue;
		if (Function && Schema->FindFunctionParameterDefaultValue(Function, Parameter, DefaultValue)) Schema->SetPinAutogeneratedDefaultValue(Pin, DefaultValue);
		else Schema->SetPinAutogeneratedDefaultValueBasedOnType(Pin);
	}

	static void NormalizeVector2DDefault(UEdGraphPin* Pin)
	{
		if (!Pin || Pin->PinType.PinSubCategoryObject != TBaseStructure<FVector2D>::Get() || Pin->DefaultValue.StartsWith(TEXT("("))) return;
		int32 YOffset = INDEX_NONE;
		if (!Pin->DefaultValue.FindChar(TEXT('Y'), YOffset) || !Pin->DefaultValue.Mid(YOffset).StartsWith(TEXT("Y="))) return;
		const FString XValue = Pin->DefaultValue.Left(YOffset).TrimEnd();
		const FString YValue = Pin->DefaultValue.Mid(YOffset);
		if (XValue.StartsWith(TEXT("X="))) Pin->DefaultValue = FString::Printf(TEXT("(%s,%s)"), *XValue, *YValue);
	}

	static void CreateFunctionParameterPin(UK2Node_WidgetTransition* Node, FName ParameterName, const UEdGraphSchema_K2* Schema)
	{
		if (!Node->IsValueTypeResolved()) return;
		UFunction* Function = GetTransitionFunction(Node->GetValueType());
		const FProperty* Parameter = FindTransitionParameter(Function, ParameterName);
		FEdGraphPinType PinType;
		if (Parameter && Schema->ConvertPropertyToPinType(Parameter, PinType))
		{
			UEdGraphPin* Pin = Node->CreatePin(EGPD_Input, PinType, ParameterName);
			FString DefaultValue;
			if (Schema->FindFunctionParameterDefaultValue(Function, Parameter, DefaultValue)) Schema->SetPinAutogeneratedDefaultValue(Pin, DefaultValue);
			else Schema->SetPinAutogeneratedDefaultValueBasedOnType(Pin);
		}
	}

	static void SetEasingDefault(UEdGraphPin* Pin, const FWidgetTransitionEasingValue& Value)
	{
		if (!Pin) return;
		const FString DefaultValue = FString::Printf(TEXT("(ControlPoint1=(X=%g,Y=%g),ControlPoint2=(X=%g,Y=%g))"), Value.ControlPoint1.X, Value.ControlPoint1.Y, Value.ControlPoint2.X, Value.ControlPoint2.Y);
		Pin->DefaultValue = DefaultValue;
		Pin->AutogeneratedDefaultValue = DefaultValue;
	}

	static bool IsInfiniteRepeat(const UEdGraphPin* Pin)
	{
		return Pin && Pin->LinkedTo.IsEmpty() && Pin->DefaultValue == TEXT("-1");
	}

	static TOptional<EWidgetTransitionValueType> GetSelectedPropertyValueType(const UK2Node_WidgetTransition* Node)
	{
		const UEdGraphPin* PropertyPathPin = Node ? Node->FindPin(WidgetPropertyPinName) : nullptr;
		const FString PropertyPath = PropertyPathPin ? PropertyPathPin->GetDefaultAsString() : FString();
		const UEdGraphPin* WidgetPin = Node ? Node->FindPin(WidgetPinName) : nullptr;
		if (PropertyPath.IsEmpty() || !WidgetPin || WidgetPin->LinkedTo.IsEmpty()) return {};

		UEdGraphPin* SourcePin = FEdGraphUtilities::GetNetFromPin(WidgetPin->LinkedTo[0]);
		UStruct* CurrentStruct = SourcePin ? Cast<UClass>(SourcePin->PinType.PinSubCategoryObject.Get()) : nullptr;
		const UK2Node_VariableGet* VariableGet = SourcePin ? Cast<UK2Node_VariableGet>(SourcePin->GetOwningNode()) : nullptr;
		UWidgetBlueprint* WidgetBlueprint = SourcePin && SourcePin->GetOwningNode() ? SourcePin->GetOwningNode()->GetTypedOuter<UWidgetBlueprint>() : nullptr;
		UWidget* DesignerWidget = VariableGet && WidgetBlueprint && WidgetBlueprint->WidgetTree ? WidgetBlueprint->WidgetTree->FindWidget(VariableGet->GetVarName()) : nullptr;
		FString RelativePath = PropertyPath;
		if (PropertyPath.StartsWith(TEXT("Slot.")))
		{
			CurrentStruct = DesignerWidget && DesignerWidget->Slot ? DesignerWidget->Slot->GetClass() : nullptr;
			RelativePath.RightChopInline(5);
		}

		TArray<FString> Segments;
		RelativePath.ParseIntoArray(Segments, TEXT("."), true);
		for (int32 Index = 0; CurrentStruct && Index < Segments.Num(); ++Index)
		{
			const FProperty* Property = FindFProperty<FProperty>(CurrentStruct, *Segments[Index]);
			if (!Property) return {};
			if (Index + 1 < Segments.Num())
			{
				const FStructProperty* StructProperty = CastField<FStructProperty>(Property);
				CurrentStruct = StructProperty ? StructProperty->Struct : nullptr;
				continue;
			}
			if (Property->IsA<FFloatProperty>() || Property->IsA<FDoubleProperty>()) return EWidgetTransitionValueType::Float;
			if (Property->IsA<FBoolProperty>()) return EWidgetTransitionValueType::Bool;
			if (const FStructProperty* StructProperty = CastField<FStructProperty>(Property))
			{
				if (StructProperty->Struct == TBaseStructure<FVector2D>::Get()) return EWidgetTransitionValueType::Vector2D;
				if (StructProperty->Struct == TBaseStructure<FLinearColor>::Get()) return EWidgetTransitionValueType::LinearColor;
			}
		}
		return {};
	}

	static bool IsDiscardableTypeSpecificPin(const UEdGraphPin* Pin)
	{
		if (!Pin || !Pin->bOrphanedPin || !Pin->LinkedTo.IsEmpty()) return false;
		const FName Name = Pin->PinName;
	return Name == FromValuePinName || Name == TimePinName || Name == DelayPinName || Name == ApplyValueBeforeDelayPinName || Name == RepeatCountPinName
			|| Name == EasingPinName
			|| Name == EasingControlPoint1PinName || Name == EasingControlPoint2PinName
			|| Name == YoYoPinName || Name == RemoveFromParentPinName || Name == UseSpringPinName
			|| Name == SpringSpeedPinName || Name == SpringBouncePinName || Name == LegacySpringFactorPinName || Name == LegacyDampingFactorPinName || Name == LegacyMaxVelocityPinName
			|| Name == LegacyCompleteTolerancePinName || Name == OnUpdatePinName || Name == OnStartedPinName || Name == OnFinishedPinName || Name == ValueTypePinName;
	}
